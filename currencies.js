const BY_CODE = Object.fromEntries(ALL.map((c) => [c.code, c]));

// Regional-indicator emoji: "IN" -> 🇮🇳. Shared currencies get a globe,
// crypto and metals a symbol.
const SYMBOLS = { BTC: "₿", ETH: "Ξ", XAU: "Au", XAG: "Ag", XPT: "Pt", XPD: "Pd" };
function flag(code) {
  const c = BY_CODE[code];
  if (!c) return "?";
  if (c.kind !== "fiat") return SYMBOLS[code] || code.slice(0, 2);
  if (!c.region) return "🌐";
  return String.fromCodePoint(...[...c.region].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}

